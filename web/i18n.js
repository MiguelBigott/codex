let idiomaActual = "es";

function t(clave, datos = {}) {
  const texto = TEXTOS[idiomaActual]?.[clave] ?? TEXTOS.es[clave] ?? clave;
  return texto.replace(/\{(\w+)\}/g, (_, k) => (datos[k] ?? `{${k}}`));
}

// tm muestra un Mensaje de Codex ({clave, datos}).
const tm = (m) => (m ? t(m.clave, m.datos || {}) : "");

const localeActual = () => IDIOMAS[idiomaActual]?.locale || "es-ES";

// aplicarIdioma traduce los textos fijos del HTML: data-t (texto), data-t-aria, data-t-title
// y data-t-placeholder.
function aplicarIdioma(idioma) {
  idiomaActual = TEXTOS[idioma] ? idioma : "es";
  document.documentElement.lang = idiomaActual;
  document.querySelectorAll("[data-t]").forEach((n) => { n.textContent = t(n.dataset.t); });
  for (const attr of ["aria", "title", "placeholder"]) {
    const nombre = attr === "aria" ? "aria-label" : attr;
    document.querySelectorAll(`[data-t-${attr}]`).forEach((n) => n.setAttribute(nombre, t(n.dataset[`t${attr[0].toUpperCase()}${attr.slice(1)}`])));
  }
}
